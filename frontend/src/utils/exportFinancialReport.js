import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'

const formatAmount = (value) =>
  `INR ${Number(value || 0).toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  })}`

export const exportFinancialReport = (report) => {
  if (!report) {
    throw new Error('No financial report available')
  }

  const doc = new jsPDF()

  const monthName = new Date(
    report.year,
    report.month - 1,
    1
  ).toLocaleString('en-IN', {
    month: 'long'
  })

  const pageWidth = doc.internal.pageSize.getWidth()

  // Header
  doc.setFillColor(30, 31, 40)
  doc.rect(0, 0, pageWidth, 40, 'F')

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(22)
  doc.text('SpendWise', 14, 19)

  doc.setFontSize(11)
  doc.text('Monthly Financial Report', 14, 28)

  doc.setTextColor(50, 50, 50)
  doc.setFontSize(12)
  doc.text(`${monthName} ${report.year}`, 14, 52)

  // Financial summary
  autoTable(doc, {
    startY: 60,
    head: [['Financial Metric', 'Amount']],
    body: [
      ['Total Income', formatAmount(report.totalIncome)],
      ['Total Expenses', formatAmount(report.totalExpenses)],
      ['Net Cash Flow', formatAmount(report.netCashFlow)],
      ['Monthly Budget', formatAmount(report.monthlyBudget)],
      ['Budget Remaining', formatAmount(report.budgetRemaining)],
      [
        'Budget Utilization',
        Number(report.monthlyBudget) > 0
          ? `${(
              (Number(report.totalExpenses) /
                Number(report.monthlyBudget)) *
              100
            ).toFixed(1)}%`
          : 'Not available'
      ],
      [
        'Cash Flow Rate',
        report.cashFlowRate !== null
          ? `${Number(report.cashFlowRate).toFixed(1)}%`
          : 'Not available'
      ],
      ['Total Transactions', String(report.transactionCount)]
    ],
    theme: 'grid',
    headStyles: {
      fillColor: [100, 108, 255]
    }
  })

  // Category spending
  const categoryRows = (report.categoryBreakdown || []).map(
    (item) => [
      item.category,
      formatAmount(item.amount),
      Number(report.totalExpenses) > 0
        ? `${(
            (Number(item.amount) /
              Number(report.totalExpenses)) *
            100
          ).toFixed(1)}%`
        : '0.0%'
    ]
  )

  const nextY = (doc.lastAutoTable?.finalY || 100) + 14

  doc.setFontSize(14)
  doc.text('Category Spending Breakdown', 14, nextY)

  autoTable(doc, {
    startY: nextY + 6,
    head: [['Category', 'Amount', 'Share']],
    body: categoryRows.length
      ? categoryRows
      : [['No expenses recorded', '-', '-']],
    theme: 'striped',
    headStyles: {
      fillColor: [100, 108, 255]
    }
  })

  // Footer
  const pageCount = doc.internal.getNumberOfPages()

  for (let page = 1; page <= pageCount; page++) {
    doc.setPage(page)
    doc.setFontSize(9)
    doc.setTextColor(120, 120, 120)

    doc.text(
      `Generated by SpendWise | Page ${page} of ${pageCount}`,
      14,
      doc.internal.pageSize.getHeight() - 12
    )
  }

  doc.save(
    `SpendWise-Report-${report.year}-${String(report.month).padStart(2, '0')}.pdf`
  )
}